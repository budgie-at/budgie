import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const LANDING_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MEDIA_ROOT = join(LANDING_ROOT, 'public', 'media');
const MANIFEST_PATH = join(LANDING_ROOT, 'src', 'generic', 'constant', 'media-manifest.constant.ts');
const OXFMT_PATH = join(LANDING_ROOT, '..', '..', 'node_modules', '.bin', 'oxfmt');
const MEDIA_LOCALES = ['en', 'fr', 'uk', 'de', 'es'];
const MEDIA_THEMES = ['light', 'dark'];
const NAME_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const VARIANTS = [
    { suffix: '@2x.avif', siblings: ['@2x.webp'], kind: 'STILL' },
    { suffix: '.webm', siblings: ['.mp4', '-poster.webp'], kind: 'MOTION' }
];
const BANNER =
    '/* Generated by `pnpm --filter @budgie-at/landing media:manifest` from `packages/landing/public/media`. Do not edit by hand. */';

const listEntries = (directory, isDirectory) =>
    readdirSync(directory, { withFileTypes: true })
        .filter(entry => (isDirectory ? entry.isDirectory() : entry.isFile() && entry.name !== '.gitkeep' && !entry.name.startsWith('.')))
        .map(entry => entry.name)
        .sort();

const collectThemeAssets = (slug, locale, theme, directory, errors) => {
    const files = listEntries(directory, false);
    const consumed = new Set();
    const assets = [];

    for (const { suffix, siblings, kind } of VARIANTS) {
        for (const fileName of files.filter(name => name.endsWith(suffix))) {
            const scene = fileName.slice(0, -suffix.length);
            const path = `media/${slug}/${locale}/${theme}/${fileName}`;
            const sceneSiblings = siblings.map(siblingSuffix => `${scene}${siblingSuffix}`);

            if (!NAME_PATTERN.test(scene)) {
                errors.push(`${path} has a scene id that is not kebab-case`);
            } else if (sceneSiblings.some(sibling => !files.includes(sibling))) {
                errors.push(`${path} is missing its ${sceneSiblings.join(' or ')} sibling`);
            } else {
                assets.push({ slug, locale, scene, theme, kind });
                [fileName, ...sceneSiblings].forEach(consumedFile => consumed.add(consumedFile));
            }
        }
    }

    for (const fileName of files.filter(name => !consumed.has(name))) {
        errors.push(`media/${slug}/${locale}/${theme}/${fileName} does not match the media naming contract`);
    }

    return assets;
};

const collectMediaAssets = () => {
    const assets = [];
    const errors = [];

    if (!existsSync(MEDIA_ROOT) || !statSync(MEDIA_ROOT).isDirectory()) {
        return { assets, errors };
    }

    for (const slug of listEntries(MEDIA_ROOT, true)) {
        if (!NAME_PATTERN.test(slug)) {
            errors.push(`media/${slug} is not a kebab-case slug`);
            continue;
        }

        for (const locale of listEntries(join(MEDIA_ROOT, slug), true)) {
            if (!MEDIA_LOCALES.includes(locale)) {
                errors.push(`media/${slug}/${locale} is not one of ${MEDIA_LOCALES.join(', ')}`);
                continue;
            }

            for (const theme of listEntries(join(MEDIA_ROOT, slug, locale), true)) {
                if (!MEDIA_THEMES.includes(theme)) {
                    errors.push(`media/${slug}/${locale}/${theme} is not one of ${MEDIA_THEMES.join(', ')}`);
                    continue;
                }

                assets.push(...collectThemeAssets(slug, locale, theme, join(MEDIA_ROOT, slug, locale, theme), errors));
            }
        }
    }

    assets.sort((a, b) => `${a.slug}/${a.scene}/${a.locale}/${a.theme}`.localeCompare(`${b.slug}/${b.scene}/${b.locale}/${b.theme}`));

    return { assets, errors };
};

const renderAsset = asset =>
    `    { slug: '${asset.slug}', locale: '${asset.locale}', scene: '${asset.scene}', theme: MediaThemeEnum.${asset.theme.toUpperCase()}, kind: MediaKindEnum.${asset.kind} }`;

const renderManifestSource = assets => {
    const lines = [BANNER];

    if (assets.length > 0) {
        lines.push(
            "import { MediaKindEnum } from '../enum/media-kind.enum';",
            "import { MediaThemeEnum } from '../enum/media-theme.enum';",
            ''
        );
    }

    lines.push("import type { MediaAssetInterface } from '../interface/media-asset.interface';", '');

    if (assets.length === 0) {
        lines.push('export const MEDIA_MANIFEST: readonly MediaAssetInterface[] = [];', '');
    } else {
        lines.push('export const MEDIA_MANIFEST: readonly MediaAssetInterface[] = [', assets.map(renderAsset).join(',\n'), '];', '');
    }

    return lines.join('\n');
};

const formatSource = filePath => {
    execFileSync(OXFMT_PATH, ['--write', filePath], { stdio: 'ignore' });

    return readFileSync(filePath, 'utf8');
};

const { assets, errors } = collectMediaAssets();

if (errors.length > 0) {
    errors.forEach(error => process.stderr.write(`media:manifest  ${error}\n`));
    process.exit(1);
}

const source = renderManifestSource(assets);

if (process.argv.includes('--check')) {
    const scratchPath = join(mkdtempSync(join(tmpdir(), 'budgie-media-')), 'media-manifest.constant.ts');

    writeFileSync(scratchPath, source, 'utf8');

    const rendered = formatSource(scratchPath);
    const committed = existsSync(MANIFEST_PATH) ? readFileSync(MANIFEST_PATH, 'utf8') : '';

    if (rendered !== committed) {
        process.stderr.write('media:manifest  manifest is stale, run pnpm media:manifest\n');
        process.exit(1);
    }

    process.stdout.write(`media:manifest  ${assets.length} asset(s) verified\n`);
} else {
    writeFileSync(MANIFEST_PATH, source, 'utf8');
    formatSource(MANIFEST_PATH);
    process.stdout.write(`media:manifest  wrote ${assets.length} asset(s) to src/generic/constant/media-manifest.constant.ts\n`);
}
